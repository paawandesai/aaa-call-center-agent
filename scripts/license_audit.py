"""Write LICENSES.md from the active Python environment and web/package-lock.json, and flag disallowed licenses."""
import importlib.metadata as md
import json
from datetime import date
import re
import sys

SKIP = {"pip"}
# Bundled licence files that the text match reads too narrowly.
OVERRIDES = {"tqdm": "MPL-2.0 AND MIT (from bundled LICENSE; unmodified)"}
DISALLOWED = ("GPL", "NON-COMMERCIAL", "NONCOMMERCIAL", "CC-BY-NC", "UNKNOWN")


KNOWN_TEXTS = (("Apache License", "Apache-2.0 (from bundled LICENSE)"), ("MIT License", "MIT (from bundled LICENSE)"),
               ("Permission is hereby granted, free of charge", "MIT (from bundled LICENSE)"),
               ("Redistribution and use in source and binary forms", "BSD (from bundled LICENSE)"))


def bundled_license(dist) -> str:
    for f in dist.files or []:
        if "licen" in f.name.lower() or "copying" in f.name.lower():
            try:
                text = f.read_text()
            except (OSError, UnicodeDecodeError):
                continue
            for needle, name in KNOWN_TEXTS:
                if needle in text:
                    return name
    return ""


def license_of(dist) -> str:
    meta = dist.metadata
    if meta.get("License-Expression"):
        return meta["License-Expression"]
    classifiers = [c for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if not classifiers or any("Other/Proprietary" in c for c in classifiers):
        found = bundled_license(dist)
        if found:
            return found
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(classifiers) or (meta.get("License") or "UNKNOWN").splitlines()[0][:60]


# Reviewed exceptions: LGPL libvips ships as an unmodified, dynamically loaded prebuilt binary inside sharp
# (image processing for next and transformers.js), which the GPL ban does not cover. MPL-2.0 dev tools are unmodified.
LGPL_OK = re.compile(r"^@img/sharp-")


def npm_rows() -> list[tuple[str, str, str, str]]:
    lock = json.load(open("web/package-lock.json"))["packages"]
    rows = []
    for key, v in lock.items():
        if not key:
            continue
        name = key.split("node_modules/")[-1]
        scope = "dev" if v.get("dev") else "dev or optional" if v.get("devOptional") else "runtime"
        rows.append((name, v.get("version", ""), v.get("license", "UNKNOWN"), scope))
    return sorted(set(rows), key=lambda r: (r[0].lower(), r[1]))


def main() -> int:
    rows = sorted(((d.metadata["Name"], d.version, OVERRIDES.get(d.metadata["Name"]) or license_of(d)) for d in md.distributions()),
                  key=lambda r: r[0].lower())
    rows = [r for r in rows if r[0] not in SKIP]
    lines = ["# Third-party licenses", "",
             "The Python table is generated by `scripts/license_audit.py` from the discovery environment "
             "(`requirements-discovery.txt`); the npm table lists `web/package-lock.json`. Models, fonts, system tools and "
             f"services come from `scripts/licenses_manual.md`. Last run {date.today().isoformat()}. "
             "No GPL, AGPL or non-commercial licenses are used.", "",
             "| Package | Version | License |", "|---|---|---|"]
    lines += [f"| {n} | {v} | {lic} |" for n, v, lic in rows]
    npm = npm_rows()
    lines += ["", "## Web app (npm, from `web/package-lock.json`)", "",
              "LGPL-3.0 entries are sharp's prebuilt libvips binaries: unmodified and dynamically loaded, not GPL-linked code. "
              "MPL-2.0 entries (axe-core, lightningcss) are unmodified dev/build tools. "
              "`onnxruntime-web` is a pre-release pulled by transformers.js; the server uses `onnxruntime-node`. Scope comes from the "
              "lockfile's flags: \"dev\" is installed only for development, \"dev or optional\" is a dev dependency that is "
              "also an optional peer of a runtime package, and everything else is \"runtime\".", "",
              "| Package | Version | License | Scope |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {lic} | {scope} |" for n, v, lic, scope in npm]
    lines += ["", open("scripts/licenses_manual.md").read().rstrip()]
    open("LICENSES.md", "w").write("\n".join(lines) + "\n")
    flagged = [r for r in rows if any(x in r[2].upper() for x in DISALLOWED)]
    flagged += [r for r in npm if any(x in r[2].upper().replace("LGPL", "") for x in DISALLOWED)
                or ("LGPL" in r[2].upper() and not LGPL_OK.match(r[0]))]
    print(f"packages={len(rows)} flagged={flagged}")
    return 1 if flagged else 0


if __name__ == "__main__":
    sys.exit(main())
